// SourceServiceInterface defines the source service.
type SourceServiceInterface interface {
	AddSource(ctx context.Context, org orgModel.Ref, source model.Source) (*model.Source, error)
	GetSources(ctx context.Context, org orgModel.Ref) ([]model.Source, error)
	GetSource(ctx context.Context, org orgModel.Ref, sourceID string) (*model.Source, error)
	UpdateSource(ctx context.Context, org orgModel.Ref, sourceID string, patch model.SourcePatch) (*model.Source, error)
	DeleteSource(ctx context.Context, org orgModel.Ref, sourceID string) error
	ResolveRequestSource(ctx context.Context, org orgModel.Ref, sourceID string) (*model.Source, error)
	ToCDSFormat(ctx context.Context, org orgModel.Ref, source model.Source, payload map[string]any) (
		map[string]any, error)
	ToSourceFormat(ctx context.Context, org orgModel.Ref, source model.Source, profile map[string]any) (
		map[string]any, error)
}

// SourceService is the default implementation.
type SourceService struct {
	transformations TransformationLookup
	destinations    DestinationLookup
}

// GetSourceService returns a new instance. Transformations and destinations are not available yet, so
// sources cannot link to them.
func GetSourceService() SourceServiceInterface {
	return NewSourceService(notConfiguredTransformations{}, notConfiguredDestinations{})
}

// NewSourceService returns a service that checks source links against the given modules.
func NewSourceService(transformations TransformationLookup, destinations DestinationLookup) *SourceService {
	return &SourceService{transformations: transformations, destinations: destinations}
}

// now is the clock of the service. The timestamps are truncated to microseconds, the precision every
// datasource stores, so the response of a write matches what a later read returns.
var now = func() time.Time { return time.Now().UTC().Truncate(time.Microsecond) }

// AddSource validates the source, generates its ID and timestamps, and stores it. A name the org already
// uses gives a 409. A child organization cannot add sources.
func (s *SourceService) AddSource(ctx context.Context, org orgModel.Ref, source model.Source) (*model.Source, error) {
	if err := suborg.RejectWrite(ctx, org.ID); err != nil {
		return nil, err
	}
	source.Name = strings.TrimSpace(source.Name)
	if err := validateSource(source); err != nil {
		return nil, err
	}
	transformationID, err := validateTransformationLink(ctx, s.transformations, org.ID, source.TransformationID)
	if err != nil {
		return nil, err
	}
	source.TransformationID = transformationID
	destinationIDs, err := validateDestinationLinks(ctx, s.destinations, org.ID, source.DestinationIDs)
	if err != nil {
		return nil, err
	}
	source.DestinationIDs = sortedIDs(destinationIDs)

	existing, err := store.GetSourceByName(ctx, source.Name, org.ID)
	if err != nil {
		return nil, err
	}
	if existing != nil {
		return nil, clientError(errors2.SourceAlreadyExists, http.StatusConflict,
			fmt.Sprintf("A source named '%s' already exists in this organization.", source.Name))
	}

	// source_id is always generated by CDS; the request schema does not accept one.
	source.SourceID = uuid.New().String()
	source.OrgID = org.ID
	source.CreatedAt = now()
	source.UpdatedAt = source.CreatedAt

	if err := store.AddSource(ctx, source); err != nil {
		return nil, err
	}
	return &source, nil
}

// GetSources returns the sources of the org, newest first. An org without sources gets an empty list.
func (s *SourceService) GetSources(ctx context.Context, org orgModel.Ref) ([]model.Source, error) {
	return store.GetSources(ctx, org.ID)
}

// GetSource returns a source of the org. An ID that is not a UUID gives a 400, and an unknown one a 404.
func (s *SourceService) GetSource(ctx context.Context, org orgModel.Ref, sourceID string) (*model.Source, error) {
	id, err := parseSourceID(sourceID)
	if err != nil {
		return nil, err
	}
	source, err := store.GetSourceByID(ctx, id, org.ID)
	if err != nil {
		return nil, err
	}
	if source == nil {
		return nil, notFound(org, id)
	}
	return source, nil
}

// UpdateSource changes the fields the patch sends and returns the updated source. A transformation_id of
// null unlinks the transformation, and destination_ids replaces the whole list. An empty patch gives a 400.
// A patch with a bad link changes nothing.
func (s *SourceService) UpdateSource(ctx context.Context, org orgModel.Ref, sourceID string,
	patch model.SourcePatch) (*model.Source, error) {
	if err := suborg.RejectWrite(ctx, org.ID); err != nil {
		return nil, err
	}
	if patch.IsEmpty() {
		return nil, EmptyUpdateError()
	}
	if patch.Description != nil {
		if err := validateDescription(*patch.Description); err != nil {
			return nil, err
		}
	}
	source, err := s.GetSource(ctx, org, sourceID)
	if err != nil {
		return nil, err
	}

	if patch.Description != nil {
		source.Description = *patch.Description
	}
	if patch.TransformationID.Set {
		transformationID, err := validateTransformationLink(ctx, s.transformations, org.ID,
			patch.TransformationID.Value)
		if err != nil {
			return nil, err
		}
		source.TransformationID = transformationID
	}
	if patch.DestinationIDs.Set {
		destinationIDs, err := validateDestinationLinks(ctx, s.destinations, org.ID, patch.DestinationIDs.Values)
		if err != nil {
			return nil, err
		}
		source.DestinationIDs = sortedIDs(destinationIDs)
	}
	source.UpdatedAt = now()
	if err := store.UpdateSource(ctx, *source); err != nil {
		return nil, err
	}
	return source, nil
}

// EmptyUpdateError is the 400 for a patch that changes nothing.
func EmptyUpdateError() error {
	return clientError(errors2.SourceEmptyUpdate, http.StatusBadRequest,
		"The request body must contain 'description', 'transformation_id' or 'destination_ids'.")
}

// DeleteSource removes a source of the org. Deleting a source that does not exist succeeds, so the call is
// idempotent. An ID that is not a UUID gives a 400.
func (s *SourceService) DeleteSource(ctx context.Context, org orgModel.Ref, sourceID string) error {
	if err := suborg.RejectWrite(ctx, org.ID); err != nil {
		return err
	}
	id, err := parseSourceID(sourceID)
	if err != nil {
		return err
	}
	return store.DeleteSource(ctx, id, org.ID)
}

// sortedIDs returns the IDs in ascending order, the order the store reads them back in, so the response of
// a write matches what a later read returns.
func sortedIDs(ids []string) []string {
	out := append([]string{}, ids...)
	sort.Strings(out)
	return out
}

func validateSource(source model.Source) error {
	if source.Name == "" || utf8.RuneCountInString(source.Name) > model.MaxNameLength {
		return clientError(errors2.SourceNameInvalid, http.StatusBadRequest,
			fmt.Sprintf("'name' must be 1-%d characters after trimming.", model.MaxNameLength))
	}
	if !isValidIconURL(source.IconURL) {
		return clientError(errors2.SourceIconURLInvalid, http.StatusBadRequest,
			fmt.Sprintf("'icon_url' must be an absolute https URL of at most %d characters.",
				model.MaxIconURLLength))
	}
	return validateDescription(source.Description)
}

func validateDescription(description string) error {
	if utf8.RuneCountInString(description) > model.MaxDescriptionLength {
		return clientError(errors2.SourceDescriptionTooLong, http.StatusBadRequest,
			fmt.Sprintf("'description' must be at most %d characters.", model.MaxDescriptionLength))
	}
	return nil
}

// isValidIconURL accepts an absolute https URL with a host, of at most MaxIconURLLength characters.
func isValidIconURL(raw string) bool {
	if raw == "" || len(raw) > model.MaxIconURLLength || strings.TrimSpace(raw) != raw {
		return false
	}
	parsed, err := url.Parse(raw)
	if err != nil {
		return false
	}
	return parsed.Scheme == "https" && parsed.Host != ""
}

// parseSourceID checks that the ID is a UUID and returns it in its canonical form.
func parseSourceID(sourceID string) (string, error) {
	parsed, err := uuid.Parse(sourceID)
	if err != nil || len(sourceID) != 36 {
		return "", clientError(errors2.SourceIDInvalid, http.StatusBadRequest,
			fmt.Sprintf("'%s' is not a valid UUID.", sourceID))
	}
	return parsed.String(), nil
}

func notFound(org orgModel.Ref, sourceID string) error {
	return clientError(errors2.SourceNotFound, http.StatusNotFound,
		fmt.Sprintf("No source with ID '%s' exists in organization '%s'.", sourceID, org.Handle))
}

func clientError(code errors2.ErrorMessage, status int, description string) error {
	return errors2.NewClientError(errors2.ErrorMessage{
		Code:        code.Code,
		Message:     code.Message,
		Description: description,
	}, status)
}
